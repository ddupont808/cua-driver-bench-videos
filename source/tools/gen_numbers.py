"""gen_numbers.py: reads results/board.parquet of the CuaDriverBench-AgentEnv dataset (read-only download) -> numbers.json
(macOS, Claude Sonnet 5.5; drivers shown: cua-driver, codex-computer-use, agent-desktop, browser-use)."""
import pandas as pd, json, sys
src = sys.argv[1]; out = sys.argv[2]; asof = sys.argv[3]
d = pd.read_parquet(src)
m = d[(d.os == 'macOS') & (d.model == 'Claude Sonnet 5.5')]
ORDER = [('cua-driver', 'Cua Driver', True), ('Codex Computer Use', 'Codex Computer Use', False), ('agent-desktop', 'Vercel Labs agent-desktop', False), ('browser-use', 'browser-use', False)]
TASKS = ['CDB-G02', 'CDB-G03', 'CDB-G04', 'IR-01', 'IR-02', 'IR-03', 'IR-04', 'MB-09']
drivers = []
for key, name, hl in ORDER:
    b = m[(m.driver == key) & (m.condition == 'background')]; f = m[(m.driver == key) & (m.condition == 'foreground')]
    drivers.append({'id': key, 'name': name, 'passed': int(b.passed.sum()), 'n': int(len(b)), 'fg_passed': int(f.passed.sum()), 'fg_n': int(len(f)),
        'disturbed': int((b.user_undisturbed == False).sum()), 'source': 'AgentEnv', 'highlight': hl,
        'per_task': [int(b[b.task == t].passed.sum()) for t in TASKS]})
n = {'_comment': 'Generated by gen_numbers.py from results/board.parquet. Single source of every number in the films; edit or regenerate, then re-render.',
 'model': 'Claude Sonnet 5.5', 'os': 'macOS', 'tasks': TASKS, 'n_tasks': 8,
 'dataset': 'huggingface.co/datasets/earakely-scale/CuaDriverBench-AgentEnv', 'asof': asof,
 'title': 'Fully passed in the background',
 'subtitle': 'macOS · 8 tasks × 5 trials = 40 trials per driver · Claude Sonnet 5.5',
 'source_line': f'AgentEnv runs on the CuaDriverBench-AgentEnv dataset, as of {asof}',
 'footnote': f"Full pass = task done, GUI-only, user undisturbed. AgentEnv's runs (Scale AI), read from the CuaDriverBench-AgentEnv dataset on {asof}; not like-for-like with Cua's own runner. Claude Sonnet 5.5. We build Cua Driver.",
 'caveat': "AgentEnv's runs, not like-for-like with Cua's own runner. Codex Computer Use runs foreground-only on Windows, so no Windows background comparison is shown. Other models rank the drivers differently.",
 'other_os_note': 'Other systems and models are in the dataset.', 'drivers': drivers}
MODELS = ['Claude Haiku 5.5', 'Claude Sonnet 5.5', 'Claude Opus 5.5', 'GPT-6 Luna', 'GPT-6.1 Sol', 'GPT-6.1 Terra']
w = d[d.os == 'Windows']; W = {'os': 'Windows', 'models': MODELS, 'drivers': {}}
for key, name in [('cua-driver', 'Cua Driver'), ('agent-desktop', 'Vercel Labs agent-desktop'), ('Codex Computer Use', 'Codex Computer Use')]:
    ent = {'name': name, 'bg': {}, 'fg': {}}
    for mo in MODELS:
        for cond, k in (('background', 'bg'), ('foreground', 'fg')):
            x = w[(w.driver == key) & (w.model == mo) & (w.condition == cond)]
            if len(x): ent[k][mo] = [int(x.passed.sum()), int(len(x))]
    W['drivers'][key] = ent
n['windows'] = W
n['windows_note'] = 'Windows: AgentEnv runs. Codex Computer Use on Windows is foreground-only (no background trials), so no Windows background comparison with it is shown.'
json.dump(n, open(out, 'w', encoding='utf8'), indent=2, ensure_ascii=False)
for x in drivers: print(x['name'], f"bg {x['passed']}/{x['n']} fg {x['fg_passed']}/{x['fg_n']} disturbed {x['disturbed']}", x['per_task'])
